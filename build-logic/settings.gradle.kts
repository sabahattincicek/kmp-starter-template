// Included build that holds the convention plugins. It reads the same version catalog as the main
// build so every version is declared once, in gradle/libs.versions.toml.
dependencyResolutionManagement {
    repositories {
        google()
        mavenCentral()
        gradlePluginPortal()
    }
    versionCatalogs {
        create("libs") {
            from(files("../gradle/libs.versions.toml"))
        }
    }
}

rootProject.name = "build-logic"
include(":convention")
